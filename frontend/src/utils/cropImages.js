export function getCropMedia(cropName) {
  if (!cropName) return CROP_MEDIA_MAP['tomato'];
  const clean = cropName.toLowerCase().trim();
  for (const [key, value] of Object.entries(CROP_MEDIA_MAP)) {
    if (clean.includes(key)) {
      return value;
    }
  }
  return CROP_MEDIA_MAP['tomato'];
}
